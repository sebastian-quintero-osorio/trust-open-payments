// Command contractgen generates wire models directly from the unchanged contract.
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"

	"go.yaml.in/yaml/v3"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
func run() error {
	b, e := os.ReadFile("op-service.openapi.yaml")
	if e != nil {
		return e
	}
	var doc map[string]any
	if e = yaml.Unmarshal(b, &doc); e != nil {
		return e
	}
	schemas := doc["components"].(map[string]any)["schemas"].(map[string]any)
	names := make([]string, 0, len(schemas))
	for name := range schemas {
		names = append(names, name)
	}
	sort.Strings(names)
	var out strings.Builder
	out.WriteString("// Code generated by go generate; DO NOT EDIT.\npackage domain\n\n")
	for _, name := range names {
		if name == "Amount" {
			continue
		}
		fmt.Fprintf(&out, "// %s is defined by op-service.openapi.yaml.\ntype %s %s\n\n", name, name, goType(schemas[name].(map[string]any), false))
	}
	code, e := format.Source([]byte(out.String()))
	if e != nil {
		return e
	}
	return os.WriteFile("internal/domain/models.gen.go", code, 0600)
}
func goType(s map[string]any, optional bool) string {
	prefix := ""
	if optional {
		prefix = "*"
	}
	if ref, ok := s["$ref"].(string); ok {
		return prefix + ref[strings.LastIndex(ref, "/")+1:]
	}
	if _, ok := s["allOf"]; ok {
		return "Amount"
	}
	if xs, ok := s["oneOf"].([]any); ok {
		for _, x := range xs {
			m := x.(map[string]any)
			if m["type"] != "null" {
				return goType(m, true)
			}
		}
	}
	typ, _ := s["type"].(string)
	if xs, ok := s["type"].([]any); ok {
		for _, x := range xs {
			if x != "null" {
				typ = x.(string)
			} else {
				prefix = "*"
			}
		}
	}
	switch typ {
	case "string":
		return prefix + "string"
	case "integer":
		return prefix + "int"
	case "boolean":
		return prefix + "bool"
	case "array":
		return "[]" + goType(s["items"].(map[string]any), false)
	case "object":
		props, _ := s["properties"].(map[string]any)
		if len(props) == 0 {
			return "map[string]any"
		}
		required := map[string]bool{}
		if xs, ok := s["required"].([]any); ok {
			for _, x := range xs {
				required[x.(string)] = true
			}
		}
		keys := make([]string, 0, len(props))
		for k := range props {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		var out strings.Builder
		out.WriteString("struct {\n")
		for _, k := range keys {
			tag := k
			if !required[k] {
				tag += ",omitempty"
			}
			quoted, _ := json.Marshal(tag)
			fmt.Fprintf(&out, "%s %s `json:%s`\n", identifier(k), goType(props[k].(map[string]any), !required[k]), quoted)
		}
		out.WriteString("}")
		return prefix + out.String()
	}
	return "any"
}
func identifier(s string) string {
	var out strings.Builder
	for _, p := range strings.Split(s, "_") {
		switch p {
		case "id", "url", "qr":
			out.WriteString(strings.ToUpper(p))
		default:
			out.WriteString(strings.ToUpper(p[:1]) + p[1:])
		}
	}
	return out.String()
}
